ERDRADIUS_KM = 6371.0


def distanz_km(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    """Haversine-Distanz in Kilometern."""
    p1, p2 = math.radians(lat1), math.radians(lat2)
    d_lat = p2 - p1
    d_lng = math.radians(lng2 - lng1)
    a = math.sin(d_lat / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(d_lng / 2) ** 2
    return 2 * ERDRADIUS_KM * math.asin(math.sqrt(a))


def normalisiere(text: str) -> str:
    text = text.strip().lower()
    for alt, neu in (("ä", "ae"), ("ö", "oe"), ("ü", "ue"), ("ß", "ss")):
        text = text.replace(alt, neu)
    return re.sub(r"[^a-z0-9]+", "", text)


def plz_praefix(text: str) -> str | None:
    """Erste zwei Ziffern einer eingegebenen PLZ, falls die Eingabe eine ist."""
    ziffern = re.findall(r"\d", text)
    if len(ziffern) < 2:
        return None
    return "".join(ziffern[:2])


def zentrum_aus_plz(text: str) -> tuple[float, float] | None:
    praefix = plz_praefix(text)
    if praefix is None:
        return None
    return PLZ_REGIONEN.get(praefix)
